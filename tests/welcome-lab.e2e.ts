import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
test('paquete real en Veltria-Lab: bienvenida, alternativas y plan sin instalar', async ({ page }) => {
  test.skip(process.env.VELTRIA_VALIDATE_LAB !== '1', 'Opt-in isolated Linux/WSL lab; no downloads')
  const descriptor = JSON.parse(execFileSync('/mnt/c/Windows/System32/wsl.exe', ['-d','Veltria-Lab','-u','veltria','--exec','python3','-c', "import glob; print(open(sorted(glob.glob('/home/veltria/lab/welcome3-20261109/data-*/.service-lock/instance.json'))[-1]).read())"], { encoding: 'utf8' }))
  const launch = await fetch(descriptor.origin + '/api/v1/control/launch', { method:'POST', headers:{ 'content-type':'application/json','x-veltria-control':descriptor.controlToken }, body:'{}' }).then(r=>r.json()) as {nonce:string}
  const errors: string[] = []; page.on('pageerror', error=>errors.push(error.message))
  await page.setViewportSize({width:1366,height:900})
  await page.goto(descriptor.origin + '/#launch=' + launch.nonce)
  await expect(page.getByRole('heading',{name:'Tu PC, lista para imaginar.'})).toBeVisible()
  await expect(page.locator('.welcome-hardware')).toContainText('RTX 4050')
  await expect(page.locator('.welcome-recommendation')).toContainText('Stable Diffusion 1.5')
  await expect(page.locator('.welcome-alternative')).toContainText('DreamShaper')
  await expect(page.getByLabel('Describe lo que imaginas')).toHaveCount(0)
  await expect(page.locator('.sidebar, dialog, .media-tabs')).toHaveCount(0)
  await page.screenshot({path:'build/lab/welcome3-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'Elegir este modelo',exact:true}).click()
  await expect(page.locator('.welcome-recommendation')).toContainText('DreamShaper')
  await page.getByRole('button',{name:'Instalar y preparar mi PC',exact:true}).click()
  await expect(page.locator('.managed-setup')).toContainText('DreamShaper')
  await expect(page.getByRole('heading',{name:'Encontramos ComfyUI. ¿Quieres usarlo?'})).toHaveCount(0)
  const install=page.getByRole('button',{name:'Instalar y preparar mi equipo',exact:true})
  await expect(install).toBeDisabled()
  await page.locator('.managed-setup').getByRole('checkbox').check()
  await expect(install).toBeEnabled()
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'build/lab/welcome3-mobile.png',fullPage:true})
  const managed=await page.evaluate(async()=>fetch('/api/v1/setup/managed').then(r=>r.json()))
  expect(managed.status).toBe('idle')
  expect(errors).toEqual([])
})
