let directory: string, child: ChildProcess, url: string
test.beforeAll(async () => {
  directory = await mkdtemp(join(tmpdir(), 'Veltria first image UI fixture '))
  child = spawn('bun', ['scripts/test-creation-host.ts'], { shell: false, stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, VELTRIA_TEST_DIR: directory } })
  url = await new Promise<string>((resolve, reject) => {
    let buffer = ''; const timer = setTimeout(() => reject(new Error('fixture timeout')), 15000)
    child.once('error', reject); child.stderr?.on('data', () => {})
    child.stdout?.on('data', chunk => { buffer += chunk.toString(); if (buffer.includes('\n')) { clearTimeout(timer); try { const ready = JSON.parse(buffer.split('\n')[0]); resolve(`${ready.origin}/#launch=${ready.nonce}`) } catch (e) { reject(e) } } })
  })
})
test.afterAll(async () => { if (child && child.exitCode === null) { const exited = new Promise(resolve => child.once('exit', resolve)); child.kill('SIGTERM'); await exited } if (directory) await rm(directory, { recursive: true, force: true }) })
